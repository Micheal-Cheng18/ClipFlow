import SwiftUI
import AppKit
import Carbon
import QuartzCore
import Combine

@MainActor final class Store: ObservableObject {
    @Published var clips: [Clip] = []
    @Published var query = ""
    @Published var paused = false
    private var change = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let url = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("ClipFlow/history.json")
    init() {
        if let data = try? Data(contentsOf: url), let saved = try? JSONDecoder().decode([Clip].self, from: data) { clips = saved }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in Task { @MainActor in self?.poll() } }
    }
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != change else { return }
        change = pb.changeCount
        guard !paused, !(pb.types ?? []).contains(where: { ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].contains($0.rawValue) }) else { return }
        var entry: Clip
        if let image = NSImage(pasteboard: pb), let tiff = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiff), let png = bitmap.representation(using: .png, properties: [:]), png.count <= 20_000_000 {
            entry = Clip(text: "图片", imageData: png)
        } else if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= 1_000_000 {
            entry = Clip(text: text)
        } else { return }
        if let i = clips.firstIndex(where: { $0.imageData == entry.imageData && $0.text == entry.text }) { let item = clips.remove(at: i); clips.insert(item, at: 0) }
        else { clips.insert(entry, at: 0) }
        var count = 0
        var imageBytes = 0
        clips = clips.filter { item in if item.pinned { return true }; count += 1; imageBytes += item.imageData?.count ?? 0; return count <= 200 && imageBytes <= 100_000_000 }
        save()
    }
    func save() {
        do { try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true); try JSONEncoder().encode(clips).write(to: url, options: [.atomic, .completeFileProtectionUnlessOpen]) } catch { NSLog("ClipFlow save failed: %@", error.localizedDescription) }
    }
    func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let data = clip.imageData {
            pb.setData(data, forType: .png)
            if let image = NSImage(data: data), let tiff = image.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        } else { pb.setString(clip.text, forType: .string) }
        change = pb.changeCount
    }
    var panelWidth: CGFloat {
        let value = UserDefaults.standard.double(forKey: "panelWidth")
        return value > 0 ? min(520, max(320, value)) : 380
    }
    var panelHeight: CGFloat { min(480, 190 + CGFloat(max(1, visible.count)) * 96) }
    var visible: [Clip] { clips.filter { query.isEmpty || $0.text.localizedCaseInsensitiveContains(query) }.sorted { $0.pinned && !$1.pinned } }
}
